"""
pixelforge - the Restaurant for Monsters pixel art engine.

Every final asset in this game is generated by this library. Nothing is
imported, traced or downloaded. Sprites are built from solids; each solid gets
a dome height field, and the resulting lambert term is POSTERISED into three
flat tones.

Style target is Stardew Valley: flat, warm, saturated, heavy dark outlines.
The dome is only used to decide WHERE the three tones fall - it never shows
through as a gradient. Smooth shading, dithered boundaries and rim lights all
read as "modern HD pixel art", which is a different genre entirely.

ART SPEC (see CLAUDE.md - do not deviate)
  native canvas   1280x720, assets authored 1:1 (no upscaling)
  tile            32x32
  light direction from upper-left, (-0.55, -0.72)
  ramp            5 entries; only indices 1/2/4 are used for shading
  shading         3 hard tones, thresholds T_SHADOW / T_LIGHT
  outline         solid 1px INK_OUTLINE, no per-material tinting
  dither          none
  rim light       none
"""
import numpy as np
import colorsys
import os

LIGHT = np.array([-0.55, -0.72], np.float32)
BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6],
                  [3, 11, 1, 9], [15, 7, 13, 5]], np.float32) / 16.0


# ---------------------------------------------------------------- colour ----
def hex2rgb(h):
    if not isinstance(h, str):       # already an rgb tuple - idempotent
        return tuple(int(v) for v in h[:3])
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb2hex(c):
    return "#%02x%02x%02x" % tuple(int(round(v)) for v in c[:3])


def ramp(base, n=5, spread=0.22, hue_shift=0.030, sat_curve=0.10):
    """Build an n-tone ramp from a base colour.

    Tuned for the Stardew Valley look: shadows go deeper and MORE saturated
    (never desaturated grey), highlights lift only a little and stay warm.
    Because the shading posteriser only uses three of these tones, each step
    has to carry real value separation on its own.

    Shadows shift cool-and-purple, highlights shift warm-and-gold. Keeping
    saturation up through the whole ramp is what gives the style its
    storybook richness instead of a washed-out look.
    """
    r, g, b = [c / 255 for c in (hex2rgb(base) if isinstance(base, str) else base)]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    out = []
    for i in range(n):
        t = (i / (n - 1)) * 2 - 1
        reach = spread * (1.5 if t < 0 else 1.0)
        nl = float(np.clip(l + t * reach * (1 - abs(l - .5) * .45), 0.05, 0.95))
        # saturation RISES into shadow and barely drops into light
        ns = float(np.clip(s + (0.30 * s * -t if t < 0 else -sat_curve * s * t),
                           0, 1))
        nh = (h + t * hue_shift) % 1.0
        out.append(tuple(int(round(c * 255)) for c in colorsys.hls_to_rgb(nh, nl, ns)))
    return out


def mix(a, b, t):
    a = hex2rgb(a) if isinstance(a, str) else a
    b = hex2rgb(b) if isinstance(b, str) else b
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(3))


def shade(c, t):
    """t<0 darken toward cool shadow, t>0 lighten toward warm highlight."""
    return mix(c, (18, 14, 34) if t < 0 else (255, 244, 214), abs(t))


def stable_seed(text):
    """Deterministic seed from a string.

    Python's built-in hash() is randomised per process, so seeding an RNG with
    it makes the asset build non-reproducible - regenerating produced visibly
    different mushrooms and garnishes. crc32 is stable across runs and
    machines.
    """
    import zlib
    return zlib.crc32(str(text).encode("utf-8"))


# ---------------------------------------------------------------- canvas ----
class Sprite:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.buf = np.zeros((h, w, 4), np.uint8)

    def copy(self):
        s = Sprite(self.w, self.h)
        s.buf = self.buf.copy()
        return s

    def px(self, x, y, col, a=255):
        # generators pass "#rrggbb" straight from palette.py as often as tuples
        if isinstance(col, str):
            col = hex2rgb(col)
        x, y = int(round(x)), int(round(y))
        if 0 <= x < self.w and 0 <= y < self.h:
            if a >= 255:
                self.buf[y, x] = (int(col[0]), int(col[1]), int(col[2]), 255)
            else:
                o = self.buf[y, x]
                f = a / 255.0
                self.buf[y, x] = (int(col[0] * f + o[0] * (1 - f)),
                                  int(col[1] * f + o[1] * (1 - f)),
                                  int(col[2] * f + o[2] * (1 - f)),
                                  max(int(o[3]), int(a)))

    def get(self, x, y):
        if 0 <= x < self.w and 0 <= y < self.h:
            return tuple(int(v) for v in self.buf[y, x])
        return (0, 0, 0, 0)

    def rect(self, x, y, w, h, col, a=255):
        for j in range(int(y), int(y + h)):
            for i in range(int(x), int(x + w)):
                self.px(i, j, col, a)

    def line(self, x0, y0, x1, y1, col, a=255):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            self.px(x0, y0, col, a)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def mask_fill(self, mask, col, a=255):
        ys, xs = np.nonzero(mask)
        for y, x in zip(ys, xs):
            self.px(int(x), int(y), col, a)

    def paste(self, other, ox=0, oy=0):
        for y in range(other.h):
            for x in range(other.w):
                p = other.buf[y, x]
                if p[3]:
                    self.px(x + ox, y + oy,
                            (int(p[0]), int(p[1]), int(p[2])), int(p[3]))

    def save(self, path):
        from PIL import Image
        d = os.path.dirname(path)
        if d:
            os.makedirs(d, exist_ok=True)
        Image.fromarray(self.buf, "RGBA").save(path)
        return path

    def alpha(self):
        return self.buf[:, :, 3] > 0


# ---------------------------------------------------------------- shapes ----
def _grid(w, h):
    return np.meshgrid(np.arange(w, dtype=np.float32),
                       np.arange(h, dtype=np.float32))


def m_ellipse(w, h, cx, cy, rx, ry):
    X, Y = _grid(w, h)
    return (((X + .5 - cx) / max(rx, .01)) ** 2
            + ((Y + .5 - cy) / max(ry, .01)) ** 2) <= 1.0


def m_rect(w, h, x, y, rw, rh):
    X, Y = _grid(w, h)
    return (X >= x) & (X < x + rw) & (Y >= y) & (Y < y + rh)


def m_round_rect(w, h, x, y, rw, rh, r):
    X, Y = _grid(w, h)
    cx = np.clip(X + .5, x + r, x + rw - r)
    cy = np.clip(Y + .5, y + r, y + rh - r)
    inside = (X >= x) & (X < x + rw) & (Y >= y) & (Y < y + rh)
    return inside & (((X + .5 - cx) ** 2 + (Y + .5 - cy) ** 2) <= r * r + r)


def m_capsule(w, h, x0, y0, x1, y1, r):
    X, Y = _grid(w, h)
    dx, dy = x1 - x0, y1 - y0
    L2 = max(dx * dx + dy * dy, 1e-6)
    t = np.clip(((X + .5 - x0) * dx + (Y + .5 - y0) * dy) / L2, 0, 1)
    px, py = x0 + t * dx, y0 + t * dy
    return ((X + .5 - px) ** 2 + (Y + .5 - py) ** 2) <= r * r


def m_poly(w, h, pts):
    X, Y = _grid(w, h)
    inside = np.zeros((h, w), bool)
    n = len(pts)
    for i in range(n):
        x0, y0 = pts[i]
        x1, y1 = pts[(i + 1) % n]
        cond = ((y0 > Y + .5) != (y1 > Y + .5))
        denom = (y1 - y0) if abs(y1 - y0) > 1e-6 else 1e-6
        xin = (x1 - x0) * (Y + .5 - y0) / denom + x0
        inside ^= cond & (X + .5 < xin)
    return inside


def m_blob(w, h, cx, cy, r, lobes, seed=0, wob=0.28):
    """Organic silhouette - sine lobes around a circle. Slimes, foliage,
    smoke, dough. Deterministic per seed so builds are reproducible."""
    rng = np.random.RandomState(seed)
    X, Y = _grid(w, h)
    ang = np.arctan2(Y + .5 - cy, X + .5 - cx)
    dist = np.sqrt((X + .5 - cx) ** 2 + (Y + .5 - cy) ** 2)
    rr = np.full_like(ang, float(r))
    for _ in range(lobes):
        f = rng.randint(2, 5)
        ph = rng.uniform(0, 6.28)
        rr = rr + r * wob / lobes * np.sin(ang * f + ph)
    return dist <= rr


def m_star(w, h, cx, cy, ro, ri, points, rot=0.0):
    pts = []
    for i in range(points * 2):
        a = rot + i * np.pi / points
        rad = ro if i % 2 == 0 else ri
        pts.append((cx + np.cos(a) * rad, cy + np.sin(a) * rad))
    return m_poly(w, h, pts)


# ------------------------------------------------------- distance / form ----
def _erode(m):
    o = m.copy()
    o[1:, :] &= m[:-1, :]
    o[:-1, :] &= m[1:, :]
    o[:, 1:] &= m[:, :-1]
    o[:, :-1] &= m[:, 1:]
    return o


def _erode_diag(m):
    o = m.copy()
    o[1:, 1:] &= m[:-1, :-1]
    o[:-1, :-1] &= m[1:, 1:]
    o[1:, :-1] &= m[:-1, 1:]
    o[:-1, 1:] &= m[1:, :-1]
    return o


def dilate(m):
    o = m.copy()
    o[1:, :] |= m[:-1, :]
    o[:-1, :] |= m[1:, :]
    o[:, 1:] |= m[:, :-1]
    o[:, :-1] |= m[:, 1:]
    return o


def dist_inside(mask):
    """Octagonal distance transform. Alternating 4- and 8-connected erosion
    approximates euclidean closely enough for form shading, fully vectorised."""
    d = np.zeros(mask.shape, np.float32)
    cur = mask.copy()
    k = 0
    while cur.any() and k < 512:
        k += 1
        d[cur] = k
        cur = _erode(cur) if k % 2 else _erode_diag(cur)
    return d


def dome(mask, bulge=1.0, flat=0.0):
    """Height field: a dome over the mask. `flat` blends toward a plateau so
    boxy props do not look like pillows."""
    d = dist_inside(mask)
    dm = d.max()
    if dm <= 0:
        return d
    t = np.clip(d / dm, 0, 1)
    h = np.sqrt(np.clip(1 - (1 - t) ** 2, 0, 1))
    h = h * (1 - flat) + t * flat
    return h * bulge


def normals(hmap, strength=2.6):
    gx = np.zeros_like(hmap)
    gy = np.zeros_like(hmap)
    gx[:, 1:-1] = (hmap[:, 2:] - hmap[:, :-2]) * .5
    gy[1:-1, :] = (hmap[2:, :] - hmap[:-2, :]) * .5
    nz = 1.0 / max(strength, .01)
    ln = np.sqrt(gx * gx + gy * gy + nz * nz)
    return -gx / ln, -gy / ln, nz / ln


# ---------------------------------------------------------------- render ----
# Stardew-style posterisation.
#
# The tone bands are picked from a 5-tone ramp rather than spread evenly across
# it: a shadow, a dominant base, and a small highlight. Ramps stay 5 entries
# long because generators index cols[3] / cols[4] directly for hand-drawn
# details - only the SHADING uses this subset.
FLAT_LEVELS = (1, 2, 4)
## Lambert thresholds. Wide middle band = the base colour owns most of the
## surface, which is what makes the style read as flat rather than moulded.
T_SHADOW = 0.50
T_LIGHT = 0.86


def render_solid(sp, mask, cols, bulge=1.0, flat=0.0, ambient=0.30,
                 light=LIGHT, rim=False, rim_str=1.0, dither=False,
                 strength=2.2, bias=0.0, alpha=255, contrast=1.0,
                 smooth=False, levels=FLAT_LEVELS):
    """Shade `mask` into sprite `sp` using colour ramp `cols` (dark -> light).

    Default mode is FLAT (Stardew Valley style): the lambert term is
    posterised into three hard tones with no dithering and no rim light.
    Smooth gradients, dithered boundaries and rim lights read as modern
    "HD pixel art" - a different genre of pixel art entirely, and not the one
    this project targets.

    Pass smooth=True to get the old continuous ramp (used almost nowhere;
    kept for gradients like the cooking heat rail).
    """
    if not mask.any():
        return
    h = dome(mask, bulge, flat)
    nx, ny, nz = normals(h, strength)
    L = light / (np.linalg.norm(light) + 1e-6)
    lam = np.clip(nx * L[0] + ny * L[1] + nz * 0.46, 0, 1)
    lam = np.clip(ambient + (1 - ambient) * lam + bias, 0, 1)
    if contrast != 1.0:
        lam = lam ** contrast

    n = len(cols)
    if smooth:
        f = lam * (n - 1)
        idx = np.floor(f).astype(np.int32)
        frac = f - idx
        if dither:
            by, bx = np.indices(mask.shape)
            thr = BAYER[by % 4, bx % 4]
            band = (frac > 0.38) & (frac < 0.74)
            idx = idx + (band & (frac > 0.30 + thr * 0.52)).astype(np.int32)
    else:
        lo, mid, hi = [min(v, n - 1) for v in levels]
        idx = np.where(lam < T_SHADOW, lo, np.where(lam < T_LIGHT, mid, hi))
        idx = idx.astype(np.int32)
    idx = np.clip(idx, 0, n - 1)

    ys, xs = np.nonzero(mask)
    for y, x in zip(ys, xs):
        sp.px(int(x), int(y), cols[idx[y, x]], alpha)

    if rim:
        edge = mask & ~_erode(mask)
        rl = -(nx * L[0] + ny * L[1])
        band = edge & (rl > 0.46)
        rc = mix(cols[-1], (255, 236, 198), .30 * rim_str)
        ys, xs = np.nonzero(band)
        for y, x in zip(ys, xs):
            sp.px(int(x), int(y), rc, alpha)


## Near-black warm brown. Stardew outlines are a single consistent dark colour
## rather than a per-material tint - it is a large part of why its sprites feel
## like one cohesive set.
INK_OUTLINE = (38, 26, 34)


def outline(sp, tint=INK_OUTLINE, amount=0.92):
    """Solid dark 1px outline around the silhouette.

    Stardew's sprites are defined by a heavy, near-uniform dark contour. The
    earlier "tint the outline from the neighbouring colour" approach gives a
    softer, more painterly edge that belongs to a different style.
    """
    a = sp.alpha()
    ring = dilate(a) & ~a
    ys, xs = np.nonzero(ring)
    for y, x in zip(ys, xs):
        near = []
        for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            p = sp.get(int(x) + dx, int(y) + dy)
            if p[3]:
                near.append(p[:3])
        if near:
            c = tuple(float(v) for v in np.mean(near, 0))
            sp.px(int(x), int(y), mix(c, tint, amount))


def drop_shadow(sp, mask, cx, cy, rx, ry, col=(24, 18, 38), a=86):
    m = m_ellipse(sp.w, sp.h, cx, cy, rx, ry)
    ys, xs = np.nonzero(m & ~mask)
    for y, x in zip(ys, xs):
        sp.px(int(x), int(y), col, a)


def occlude(sp, mask, amount=0.5, radius=2, tint=(30, 22, 48)):
    """Darken pixels of `mask` near its contact edges - cheap ambient occlusion."""
    d = dist_inside(mask)
    ys, xs = np.nonzero(mask & (d <= radius) & (d > 0))
    for y, x in zip(ys, xs):
        p = sp.get(int(x), int(y))
        if p[3]:
            t = amount * (1 - (d[y, x] - 1) / max(radius, 1))
            sp.px(int(x), int(y), mix(p[:3], tint, float(np.clip(t, 0, 1))), p[3])


def glow(sp, x, y, r, col, strength=0.55):
    for j in range(int(y - r), int(y + r + 1)):
        for i in range(int(x - r), int(x + r + 1)):
            d = np.hypot(i + .5 - x, j + .5 - y)
            if d <= r:
                p = sp.get(i, j)
                if p[3]:
                    t = strength * (1 - d / r) ** 2
                    sp.px(i, j, mix(p[:3], col, float(t)), p[3])


def sheet(frames, path, cols=None):
    """Pack frames into a strip. Returns (path, frame_w, frame_h, count)."""
    from PIL import Image
    n = len(frames)
    cols = cols or n
    rows = (n + cols - 1) // cols
    fw, fh = frames[0].w, frames[0].h
    img = Image.new("RGBA", (fw * cols, fh * rows), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        img.paste(Image.fromarray(f.buf, "RGBA"), ((i % cols) * fw, (i // cols) * fh))
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    img.save(path)
    return path, fw, fh, n


