def text(sp, s, x, y, col, spacing=1, shadow=None):
    """Draw uppercase 5x7 text. Returns advance width."""
    cx = x
    for ch in s.upper():
        g = FONT.get(ch)
        if g is None:
            cx += 3 + spacing
            continue
        for j, row in enumerate(g):
            for i, bit in enumerate(row):
                if bit == "1":
                    if shadow is not None:
                        sp.px(cx + i, y + j + 1, shadow)
                    sp.px(cx + i, y + j, col)
        cx += 5 + spacing
    return cx - x


def text_w(s, spacing=1):
    return max(0, len(s) * (5 + spacing) - spacing)
